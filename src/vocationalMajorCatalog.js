export const VOCATIONAL_MAJOR_CATALOG = GROUPS.flatMap(([majorCategory, professionalClass, majors]) => majors.map((name) => ({
  name,
  professionalClass,
  majorCategory,
  aliases: Object.entries(ALIASES).filter(([, canonical]) => canonical === name).map(([alias]) => alias),
})))

const normalize = (value) => String(value ?? '').replace(/\s+/g, '').trim()
const CATALOG_INDEX = new Map()
VOCATIONAL_MAJOR_CATALOG.forEach((entry) => {
  CATALOG_INDEX.set(normalize(entry.name), { ...entry, matchedName: entry.name, alias: false })
  entry.aliases.forEach((alias) => CATALOG_INDEX.set(normalize(alias), { ...entry, matchedName: alias, alias: true }))
})

export function findVocationalMajor(value) {
  return CATALOG_INDEX.get(normalize(value)) ?? null
}

export function vocationalMajorSuggestions(query = '', limit = 18) {
  const needle = normalize(query)
  const labels = VOCATIONAL_MAJOR_CATALOG.flatMap((entry) => [entry.name, ...entry.aliases])
  return [...new Set(labels)]
    .filter((label) => !needle || normalize(label).includes(needle))
    .sort((a, b) => a.localeCompare(b, 'zh-Hans-CN'))
    .slice(0, limit)
}
